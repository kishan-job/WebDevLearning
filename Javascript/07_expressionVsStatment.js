// A statement is a complete unit of code that performs some action. In this case, the statement declares a variable named name and assigns it the value "kishan". This statement does not produce a value; instead, it performs an action of creating a variable and assigning it a value.

// In contrast, an expression is a piece of code that evaluates to a value.Expressions can be nested within statements, but a statement itself does not produce a value.In the provided code, "kishan" is an expression, but the entire line var name = "kishan"; is a statement because it's a complete instruction in JavaScript.

